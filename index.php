            function parseDepartureMinutes(option){
                var raw = '';
                if (option && typeof option === 'object') {
                    raw = (option.label || option.value || '') + '';
                } else {
                    raw = option + '';
                }
                raw = raw.toLowerCase().replace(/\./g, ':').trim();
                var match = raw.match(/(\d{1,2}):(\d{2})\s*(am|pm)?/);
                if (!match) {
                    return Number.POSITIVE_INFINITY;
                }
                var hour = parseInt(match[1], 10);
                var minutes = parseInt(match[2], 10);
                var modifier = match[3];
                if (modifier === 'pm' && hour < 12) {
                    hour += 12;
                } else if (modifier === 'am' && hour === 12) {
                    hour = 0;
                }
                return hour * 60 + minutes;
            }

            function isPremiumSpecialDate(context){
                var normalized = context && context.travelDate ? normalizeDateInput(context.travelDate) : '';
                if (!normalized) {
                    return false;
                }
                var target = Date.parse(normalized);
                if (isNaN(target)) {
                    return false;
                }
                var start = Date.parse('2026-01-02');
                var end = Date.parse('2026-01-04');
                return !isNaN(start) && !isNaN(end) && target >= start && target <= end;
            }

