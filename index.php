            function isPremiumBlockedDeparture(option, context){
                var minutes = parseDepartureMinutes(option);
                if (!isFinite(minutes)) {
                    return false;
                }
                var premiumSingleDayMinutes = [
                    (9 * 60 + 40),  // 9:40 am
                    (16 * 60 + 30), // 4:30 pm
                    (18 * 60 + 20), // 6:20 pm (Voi -> Nairobi)
                    (13 * 60 + 40)  // 1:40 pm (Voi -> Mombasa)
                ];
                var isSingleDay = isPremiumSpecialDate(context);
                if (premiumSingleDayMinutes.indexOf(minutes) !== -1) {
                    return !isSingleDay;
                }
                return minutes === (9 * 60 + 45);
            }

            function sortDepartureOptions(options){
                if (!Array.isArray(options) || !options.length) {
                    return options;
                }
                var selectOption = options.find(function(option){ return option && option.value === ''; });
                var rest = options.filter(function(option){ return !(option && option.value === ''); });
                rest.sort(function(a, b){
                    return parseDepartureMinutes(a) - parseDepartureMinutes(b);
                });
                return selectOption ? [selectOption].concat(rest) : rest;
            }

            function isDateInSpecialRange(config, travelDate){
                var normalized = normalizeDateInput(travelDate);
                if (!normalized) {
                    return false;
                }
                var target = Date.parse(normalized);
                if (isNaN(target)) {
                    return false;
                }
                var hasRange = !!(config.start_date || config.end_date);
                if (hasRange) {
                    var start = config.start_date ? Date.parse(config.start_date) : target;
                    var end = config.end_date ? Date.parse(config.end_date) : target;
                    if (isNaN(start) || isNaN(end)) {
                        return false;
                    }
                    return target >= start && target <= end;
                }
                if (config.travel_date) {
                    return config.travel_date === normalized;
                }
                return false;
            }

