<script>
    jQuery(document).ready(function() {
        var dropZone = jQuery('#drop_zone');

        dropZone.on('dragover', function(e) {
            e.preventDefault();
            e.stopPropagation();
            jQuery(this).addClass('dragging');
        });

        dropZone.on('dragleave', function(e) {
            e.preventDefault();
            e.stopPropagation();
            jQuery(this).removeClass('dragging');
        });

        dropZone.on('drop', function(e) {
            e.preventDefault();
            e.stopPropagation();
            jQuery(this).removeClass('dragging');

            var files = e.originalEvent.dataTransfer.files;
            if (validateImage(files[0])) {
                jQuery('#id_front').prop('files', files);
                previewFile(files[0]);
            }
        });

        jQuery('#id_front').change(function() {
            if (validateImage(this.files[0])) {
                previewFile(this.files[0]);
            }
        });

        function previewFile(file) {
            var reader = new FileReader();
            reader.onload = function(e) {
                jQuery('#preview_img').attr('src', e.target.result);
                jQuery('#image_preview').show();
            }
            reader.readAsDataURL(file);
        }

        function validateImage(file) {
            var allowedTypes = ['image/jpeg', 'image/jpg', 'image/png', 'image/gif'];
            if (file && allowedTypes.includes(file.type)) {
                jQuery('.error-message').remove();
                return true;
            } else {
                displayError('Invalid file type. Please select an image.');
                return false;
            }
        }

        function displayError(message) {
            jQuery('.error-message').remove(); // Clear existing errors
            var errorMessageHTML = '<p class="error-message" style="color: red;">' + message + '</p>';
            jQuery(dropZone).after(errorMessageHTML);
        }
    });
</script>


