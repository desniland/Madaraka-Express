            function findSpecialExpressDeparture(context, configList){
                if (!context || context.trainType !== 'express') {
                    return null;
                }
                var fromName = normalizeStationName(context.fromName);
                var toName = normalizeStationName(context.toName);
                if (!fromName || !toName || !context.travelDate) {
                    return null;
                }
                var configs = Array.isArray(configList) ? configList : SPECIAL_EXPRESS_DEPARTURES;
                for (var i = 0; i < configs.length; i++) {
                    var config = configs[i];
                    if (!isDateInSpecialRange(config, context.travelDate)) {
                        continue;
                    }
                    var routes = getConfigRoutes(config);
                    for (var r = 0; r < routes.length; r++) {
                        if (normalizeStationName(routes[r].from) === fromName &&
                            normalizeStationName(routes[r].to) === toName) {
                            return {
                                config: config,
                                route: routes[r]
                            };
                        }
                    }
                }
                return null;
            }

