            function padTwoDigits(value){
                var number = parseInt(value, 10);
                if (isNaN(number)) {
                    return '00';
                }
                return number < 10 ? '0' + number : number.toString();
            }

            function normalizeStationName(name){
                var normalized = (name || '').toLowerCase().replace(/\s+/g,' ').trim();
                normalized = normalized.replace(/\sterminus\b/g, '').trim();
                return normalized;
            }

            function normalizeDateInput(value){
                if (!value) {
                    return '';
                }
                value = value.trim();
                if (value === '') {
                    return '';
                }
                if (/^\d{4}-\d{2}-\d{2}$/.test(value)) {
                    return value;
                }
                var parts = value.split('/');
                if (parts.length === 3) {
                    var month = padTwoDigits(parts[0]);
                    var day = padTwoDigits(parts[1]);
                    var year = parts[2];
                    if (year.length === 2) {
                        year = '20' + year;
                    }
                    return year + '-' + month + '-' + day;
                }
                var parsedDate = new Date(value);
                if (!isNaN(parsedDate.getTime())) {
                    return parsedDate.getFullYear() + '-' + padTwoDigits(parsedDate.getMonth() + 1) + '-' + padTwoDigits(parsedDate.getDate());
                }
                return '';
            }

            function formatSpecialTimeLabel(timeValue){
                if (!timeValue) {
                    return '9:45 am';
                }
                var normalized = timeValue.replace('.', ':');
                var parts = normalized.split(':');
                if (parts.length < 2) {
                    return timeValue;
                }
                var hour = parseInt(parts[0], 10);
                if (isNaN(hour)) {
                    return timeValue;
                }
                var minutes = padTwoDigits(parts[1]);
                var suffix = hour >= 12 ? ' pm' : ' am';
                var hour12 = hour % 12;
                if (hour12 === 0) {
                    hour12 = 12;
                }
                return hour12 + ':' + minutes + suffix;
            }

            function formatPremiumOptionValue(optionValue, normalizedValue, context){
                if (!isPremiumSpecialDate(context)) {
                    return optionValue || normalizedValue;
